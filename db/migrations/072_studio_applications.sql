-- 072: Studio applications (Studio V1A, D1). One row per enrolled application: trusted, tenant-scoped configuration that says where a walkthrough may be authored.
-- Owner: dap_owner (applied by the migration runner as dap_owner). Same guards and tenant mechanism as 070.
-- Grants: SELECT, INSERT, UPDATE for dap_app only (no DELETE, no TRUNCATE): an application is never removed, only disabled.
-- RLS: enabled AND forced; the policy compares tenant_id to NULLIF(current_setting('app.tenant_id', true), '')::uuid so an unset tenant setting yields zero rows
-- instead of a cast error.
-- Ids are generated by the host (`app-` + 12 lowercase hex). Origins are stored NORMALISED by the host (scheme://host[:port], no path); the checks below are a
-- second line of defence for the SHAPE (http(s) scheme, no credentials/path/space, 1..5 origins, the primary origin among them), not a replacement for the host's
-- validator. Every statement is idempotent.

DO $$
BEGIN
  IF current_user <> 'dap_owner' THEN RAISE EXCEPTION 'Studio application migration requires dap_owner'; END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.studio_applications (
  tenant_id uuid NOT NULL,
  application_id text NOT NULL CHECK (application_id ~ '^app-[a-f0-9]{12}$'),
  name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 80),
  origin text NOT NULL CHECK (char_length(origin) BETWEEN 8 AND 200 AND origin ~ '^https?://[^/?#@[:space:]]+$'),
  allowed_origins text[] NOT NULL CHECK (
    cardinality(allowed_origins) BETWEEN 1 AND 5
    AND array_to_string(allowed_origins, ' ') ~ '^https?://[^/?#@[:space:]]{1,190}( https?://[^/?#@[:space:]]{1,190}){0,4}$'
    AND origin = ANY (allowed_origins)),
  environment text NOT NULL CHECK (environment IN ('development', 'test')),
  registry_id text NOT NULL CHECK (registry_id ~ '^[a-z][a-z0-9-]{0,31}$'),
  enabled boolean NOT NULL DEFAULT true,
  created_by text NOT NULL CHECK (char_length(created_by) BETWEEN 1 AND 256),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_by text NOT NULL CHECK (char_length(updated_by) BETWEEN 1 AND 256),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (tenant_id, application_id)
);

DO $$
BEGIN
  IF (SELECT pg_get_userbyid(relowner) FROM pg_class WHERE oid = 'public.studio_applications'::regclass) <> 'dap_owner' THEN
    RAISE EXCEPTION 'Studio applications table must be owned by dap_owner';
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS studio_applications_tenant_updated_idx ON public.studio_applications (tenant_id, updated_at DESC);

ALTER TABLE public.studio_applications ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.studio_applications FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON public.studio_applications;
CREATE POLICY tenant_isolation ON public.studio_applications
  USING (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid)
  WITH CHECK (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid);

REVOKE ALL ON TABLE public.studio_applications FROM PUBLIC, dap_app;
GRANT SELECT, INSERT, UPDATE ON TABLE public.studio_applications TO dap_app;
